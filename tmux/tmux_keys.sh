# Detach from current session
Ctrl-b d

# Rename current session
Ctrl-b $ [delete previous name and enter new]

# Switch to previous "(" or next ")" session
Ctrl-b (

# Choose current session interactively 
Ctrl-b s 
=================================================

# Split current pane into two, left and right (%) or up and down (")
Ctrl-b %

# Show panes id
Ctrl-b q

#Switch to specific pane (example 1)
Ctrl-b q 1

# Resize pane (Up, Down, Left, Right Arrows)
Ctrl-b Alt-Arrow

# Kill current pane interactive (confirm with yes or no)
Ctrl-b x

# Toggle zoom mode for current pane (put pane over entire window)
# Same command to switch back
Ctrl-b z

# Select one of 5 preset window modes-pane positions (1-5)
Ctrl-b Alt-1
=================================================

# Create new window (current one is marked with *)
Ctrl-b c

# Change window name
Ctrl-b , [enter name]

# Switch to next window
Ctrl-b n

# Switch to last selected window (marked with "-" in bar)
Ctrl-b l

# Choose current window interactively 
Ctrl-b w

# Kill the current window
Ctrl-b &

# Switch windows
Shift-Arrow left
Shift-Arrow right

# Reorder windows in tab
Ctrl-Shift-Arrow left
Ctrl-Shift-Arrow right 

